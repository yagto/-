/* ============================================================
   config.js — 开关集中在这里
   ============================================================ */

window.Resume = window.Resume || {};

(function (R) {
  'use strict';

  const params = new URLSearchParams(location.search);

  R.config = {
    /* ------------------------------------------------------------
       AI 分身
       ------------------------------------------------------------
       ⚠️ 密钥就写在这里 —— 这是刻意的选择，不是疏忽。

       静态站点没有服务端，密钥只能跟着页面一起发给访客。
       任何打开开发者工具的人都能看到它，网页的源码里也能直接搜到。

       所以两件事必须守住：
         1. 这把钥匙单独设一个**低额度**，别和其他项目共用；
         2. 哪天要把额度调高，先换一把新钥匙。

       想改成走中转（密钥只留在服务端），把 ENDPOINT 换成中转地址、
       把 KEY 清空即可。中转那边照 ai.js 第 6 节的契约实现，
       前端其余代码一行都不用改。
       ------------------------------------------------------------ */
    AI: {
      KEY: '',
      ENDPOINT: 'https://api.deepseek.com/chat/completions',
      MODEL: 'deepseek-flash',

      /** 超过这个时间还没回来就放弃，回落到本地问答库（毫秒） */
      TIMEOUT_MS: 10000,

      /** 每个访客每次打开页面最多问几句。挡手滑连点和死循环，不挡真人 */
      MAX_PER_SESSION: 30,

      /** 单条提问截断长度，防止有人拿它当免费写作工具 */
      MAX_QUESTION_CHARS: 200
    },

    /** 分屏吸附总开关 */
    SNAP: true,

    /** ?debug=1 时暴露 Resume.debug 工具 */
    DEBUG: params.has('debug'),

    /** ?plain=1 直接以精简模式打开（放邮件签名里用） */
    PLAIN: params.has('plain'),

    /** 低于此宽度一律降级（不做吸附、技能改为单列等） */
    MIN_DESKTOP_WIDTH: 768
  };

})(window.Resume);
